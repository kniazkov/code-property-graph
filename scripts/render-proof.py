#!/usr/bin/env python3
"""Publish traceability without treating inspected tests as execution evidence."""
import argparse
import importlib.util
import json
import re
import subprocess
from pathlib import Path
from urllib.parse import quote

spec=importlib.util.spec_from_file_location('requirements_renderer',Path(__file__).with_name('render-requirements.py'))
g=importlib.util.module_from_spec(spec);spec.loader.exec_module(g)
v=g.v
DATA=g.DATA
ROOT=g.ROOT


def literal(value):
    fence='`'*(max([len(s) for s in re.findall(r'`+',value)]+[2])+1)
    return '\n'.join([fence+'text',value,fence])


def pinned(path, revision):
    return 'https://github.com/kniazkov/code-property-graph/blob/'+revision+'/'+quote(path,safe='/')


def validate_inspections(rows, records, root):
    ids={r['id']:r for r in records};seen=set()
    fields={'requirement_id','check_id','path','method','assertion','revision','property','limitations'}
    for m in rows:
        v.require(set(m)==fields and all(isinstance(x,str) and x.strip() for x in m.values()),'invalid inspection fields')
        v.require(m['requirement_id'] in ids,'dangling inspection requirement')
        v.require(m['check_id'] in {c['id'] for c in ids[m['requirement_id']]['proposed_checks']},'dangling inspection check')
        key=(m['requirement_id'],m['check_id'],m['path'],m['method'],m['assertion'],m['revision'])
        v.require(key not in seen,'duplicate inspection');seen.add(key)
        v.require(re.fullmatch('[0-9a-f]{40}',m['revision']),'invalid inspection revision')
        v.local(root,m['path'])
        run=subprocess.run(['git','show',m['revision']+':'+m['path']],cwd=root,text=True,capture_output=True)
        v.require(run.returncode==0 and m['method'] in run.stdout and m['assertion'] in run.stdout,'missing pinned method/assertion')


def render(records, dispositions, ledger, sources, inspections, root=ROOT):
    v.validate(records,dispositions,ledger,sources,root=root)
    validate_inspections(inspections,records,root)
    out=['<!-- Generated by scripts/render-proof.py; edit records and proof-inspections.json. -->',
        '# Requirement evidence and gaps','',
        'This is a traceability report, not a certificate of C++03 conformance. '
        'A test name or assertion excerpt alone does not establish all conditions of a requirement. '
        'The generator validates references; it never runs test commands.', '',
        '[Requirements](standards/cpp/cpp03/REQUIREMENTS.md) · '
        '[Source index](standards/cpp/cpp03/SOURCE-INDEX.md) · '
        '[Evidence conventions](standards/cpp/cpp03/requirements/proof.md)', '',
        f'{len(records)} requirements; {sum(len(r["evidence"]) for r in records)} recorded execution entries; '
        f'{len(inspections)} inspected assertion mappings. Inspections are not executions.', '',
        '## Requirement navigation','', '| Requirement | Edition / locators | Verification | Recorded executions |','|---|---|---|---:|']
    for r in sorted(records,key=lambda r:r['id']):
        b=r['basis'];out.append('| '+ ' | '.join([g.link(r['id']),g.text(b['source_id']+' / '+', '.join(sorted(b['locators']))),g.text(r['states']['verification']),str(len(r['evidence']))])+' |')
    for r in sorted(records,key=lambda r:r['id']):
        id=r['id'];b=r['basis']
        out += ['',f'<a id="{g.anchor(id)}"></a>',f'## {id}', '',
            g.link(id,'standards/cpp/cpp03/REQUIREMENTS.md')+' — '+g.text(r['title']), '',
            '**Source:** '+g.text(b['source_id']+'; '+b['kind']+'; '+b['confidence']+'; '+', '.join(sorted(b['locators']))), '',
            '**States:** '+g.text('; '.join(k+'='+r['states'][k] for k in ('readiness','implementation','verification'))), '',
            '**Verification owner:** #'+str(r['status_owners']['verification']), '',
            '### Proposed checks', '']
        for c in sorted(r['proposed_checks'],key=lambda c:c['id']):
            results=[e for e in r['evidence'] if e['check_id']==c['id']]
            status='No recorded execution.' if not results else 'Recorded results: '+', '.join(sorted({e['result'] for e in results}))+'. No rerun implied.'
            out += ['- '+g.text(c['id']+': '+c['description']+' '+status)]
        if not r['proposed_checks']: out += ['None proposed; absence is not verification.']
        out += ['', '### Inspected existing assertions — not run', '']
        ms=sorted((m for m in inspections if m['requirement_id']==id),key=lambda m:json.dumps(m,sort_keys=True))
        if not ms:out += ['No inspected mapping recorded.']
        for m in ms:
            out += [f'[{g.text(m["path"])}]({pinned(m["path"],m["revision"])})', '',
                '**Method:** '+g.text(m['method'])+'; **check:** '+g.text(m['check_id']), '',
                '**Inspected revision:** '+m['revision'], '',literal(m['assertion']), '',
                '**Exact property:** '+g.text(m['property']), '', '**Coverage limits:** '+g.text(m['limitations']), '']
        out += ['', '### Recorded execution evidence', '',
            'Pinned results are historical records. This generation did not execute them; they do not prove the current head behaves identically.', '']
        if not r['evidence']:out += ['None. Proposed checks and inspected assertions cannot supply a pass result.']
        for e in sorted(r['evidence'],key=lambda e:json.dumps(e,sort_keys=True)):
            out += [f'[{g.text(e["path"])}]({pinned(e["path"],e["revision"])})', '',
                '**Check:** '+g.text(e['check_id'])+'; **recorded result:** '+e['result']+'; **revision:** '+e['revision'], '',
                '**Exact recorded assertion:**', '', literal(e['assertion']), '', '**Recorded command (not executed by this generator):**', '',literal(e['command'])]
    out += ['', '## Reverse navigation: test file to requirement', '',
        '| Test file | Requirement | Relationship |','|---|---|---|']
    reverse={(m['path'],m['requirement_id'],'Inspected only') for m in inspections}
    reverse.update((e['path'],r['id'],'Recorded execution: '+e['result']) for r in records for e in r['evidence'])
    for path,id,kind in sorted(reverse):out.append('| '+g.text(path)+' | '+g.link(id)+' | '+kind+' |')
    if not reverse:out += ['', 'No test-file mappings recorded.']
    return '\n'.join(out)+'\n'


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    records=[r for p in sorted((DATA/'records').glob('*.jsonl')) for r in v.lines(p)]
    content=render(records,v.lines(DATA/'dispositions.jsonl'),v.read(DATA/'ids.json'),v.load_sources(),v.read(DATA/'proof-inspections.json')).encode('utf-8')
    target=ROOT/'docs/PROOF.md'
    if args.check:
        if not target.exists() or target.read_bytes()!=content:raise SystemExit('Stale generated file: docs/PROOF.md')
    else:target.write_bytes(content)
    print('Proof '+('checked' if args.check else 'written'))

if __name__=='__main__':main()
