#!/usr/bin/env python3
"""Render validated requirement cards and complete source metadata indexes."""
import argparse
import importlib.util
import json
import re
from pathlib import Path

spec = importlib.util.spec_from_file_location('requirement_validation', Path(__file__).with_name('check-requirements.py'))
v = importlib.util.module_from_spec(spec)
spec.loader.exec_module(v)
ROOT = v.ROOT
DATA = v.DATA


def text(value):
    """Keep authored text literal in Markdown, including table and HTML syntax."""
    value = str(value).replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    return re.sub(r'([\\`*_{}\[\]()#+.!|~-])', r'\\\1', value).replace('\n', '<br>')


def anchor(id):
    return id.lower()


def link(id, prefix=''):
    return f'[{id}]({prefix}#{anchor(id)})'


def render(records, dispositions, ledger, sources, root=ROOT):
    # Validate before constructing any output, including reciprocal source links.
    v.validate(records, dispositions, ledger, sources, root=root)
    records = sorted(records, key=lambda r: r['id'])
    ds = {(d['source_id'], d['locator']): d for d in dispositions}
    index = []
    for source, meta in sorted(sources.items()):
        for locator in sorted(meta['locators']):
            d = ds.get((source, locator))
            index.append(dict(source_id=source, locator=locator,
                status=d['status'] if d else 'unprocessed',
                requirement_ids=sorted(d['requirement_ids']) if d else [],
                justification=d['justification'] if d else 'No authored disposition; research ownership remains unchanged.',
                question_issue=d['question_issue'] if d else None))
    pending = sum(r['status'] == 'unprocessed' for r in index)
    intro = ['<!-- Generated by scripts/render-requirements.py; edit JSONL inputs. -->',
        '# C++03 requirements', '',
        f'{len(records)} authored requirements. {pending} of {len(index)} source locators have no authored disposition.', '',
        'This partial registry does not establish ISO completeness or implementation conformance. '
        'A linked paragraph may contain additional obligations. Readiness, implementation and verification are independent.', '',
        '[Source index](SOURCE-INDEX.md) · [Authoring contract](requirements/README.md)', '',
        '| Requirement | Title | Readiness | Implementation | Verification |', '|---|---|---|---|---|']
    for r in records:
        intro.append('| '+ ' | '.join([link(r['id']),text(r['title']),*[text(r['states'][s]) for s in ('readiness','implementation','verification')]])+' |')
    for r in records:
        b = r['basis']
        provisional = r['states']['readiness'] != 'reviewed' or b['confidence'] in ('draft_only','unresolved')
        intro += ['', f'<a id="{anchor(r["id"])}"></a>', f'## {r["id"]}: {text(r["title"])}', '',
            '**PROVISIONAL**' if provisional else '**Reviewed text; consult verification state separately.**', '',
            f'**States:** readiness={r["states"]["readiness"]}; implementation={r["states"]["implementation"]}; verification={r["states"]["verification"]}.', '',
            f'**Identity:** {text(r["semantic_key"])}; owner #{r["owner_issue"]}.', '',
            '**Status owners:** '+ '; '.join(f'{k}: #{n}' for k,n in sorted(r['status_owners'].items()))+'.', '',
            '**Basis:** '+text(f'{b["source_id"]} ({b["kind"]}); {b["confidence"]}; '+', '.join(sorted(b['locators'])))+'.', '', text(b['review_note']), '']
        for label, val in [('Conditions',r['conditions']),('Exceptions',r['exceptions']),('Rule',r['rule']),('Classification',r['classification']),('CPG consequence',r['cpg_consequence']),('Platform policy',r['platform_policy'])]:
            intro += [f'**{label}:**', '']
            intro += (['- '+text(x) for x in val] or ['None.']) if isinstance(val,list) else [text(val)]
            intro += ['']
        intro += ['**Dependencies:** '+(', '.join(link(x) for x in sorted(r['dependencies'])) or 'None.') , '',
            '**Applicability:** '+text(r['applicability']['status']+' — '+r['applicability']['justification']), '', '**Proposed checks (not execution evidence):**', '']
        intro += ['- '+text(c['id'])+': '+text(c['description']) for c in sorted(r['proposed_checks'],key=lambda c:c['id'])] or ['None.']
        intro += ['', '**Actual evidence:**', '']
        # JSON preserves every assertion, revision and command without Markdown execution/link interpretation.
        if r['evidence']:
            payload=json.dumps(sorted(r['evidence'],key=lambda e:json.dumps(e,sort_keys=True)),ensure_ascii=False,sort_keys=True,indent=2)
            fence='`'*(max([len(x) for x in re.findall(r'`+',payload)]+[2])+1)
            intro += [fence+'json',payload,fence]
        else: intro += ['None recorded; no execution claim.']
        intro += ['', '**Open questions:**', '']
        intro += ['- #'+str(q['issue'])+': '+text(q['question']) for q in sorted(r['questions'],key=lambda q:(q['issue'],q['question']))] or ['None.']
    reverse=['<!-- Generated by scripts/render-requirements.py; edit JSONL inputs. -->','# Source-to-requirement index','',
        'Indexes refer to catalogue editions, not interchangeable draft paragraph numbers. '
        'Unprocessed means no authored disposition, not an implementation failure or a statement that no requirement exists. '
        'A requirements disposition does not exhaust its paragraph.', '',
        '[Requirements](REQUIREMENTS.md) · [Complete machine-readable index](requirements/source-index.json) · '
        '[Research ownership](../../../research-ownership/index.md)', '',
        '## Authored dispositions','', '| Source | Locator | Status | Requirements | Question | Justification |','|---|---|---|---|---|---|']
    for d in index:
        if d['status']=='unprocessed': continue
        reverse.append('| '+' | '.join([text(d['source_id']),text(d['locator']),text(d['status']),', '.join(link(x,'REQUIREMENTS.md') for x in d['requirement_ids']) or 'None', '#'+str(d['question_issue']) if d['question_issue'] else 'None',text(d['justification'])])+' |')
    reverse += ['', '## Unprocessed source sections', '',
        'Counts group exact unprocessed locators by source and section. The JSON index lists every locator individually; these groups do not claim contiguous paragraph ranges.', '',
        '| Source | Section | Unprocessed locators |','|---|---|---:|']
    groups={}
    for d in index:
        if d['status']=='unprocessed':
            parts=d['locator'].split(':'); key=(d['source_id'],parts[1] if len(parts)>2 else d['locator'])
            groups[key]=groups.get(key,0)+1
    for (source,section),count in sorted(groups.items()): reverse.append(f'| {text(source)} | {text(section)} | {count} |')
    if not groups: reverse += ['','No locators without a disposition. This alone does not establish completeness.']
    unprocessed={}
    for d in index:
        if d['status']=='unprocessed':
            parts=d['locator'].split(':'); section=parts[1] if len(parts)>2 else d['locator']
            unprocessed.setdefault(d['source_id'],{}).setdefault(section,[]).append(d['locator'])
    # Keep the metadata-only remainder compact, with one exact section list per line.
    machine=['{', '  "dispositions": '+json.dumps([d for d in index if d['status']!='unprocessed'],ensure_ascii=False,sort_keys=True)+',', '  "unprocessed": {']
    for si,(source,sections) in enumerate(sorted(unprocessed.items())):
        machine.append('    '+json.dumps(source)+': {')
        for i,(section,locators) in enumerate(sorted(sections.items())):
            machine.append('      '+json.dumps(section)+': '+json.dumps(locators)+(',' if i+1<len(sections) else ''))
        machine.append('    }'+(',' if si+1<len(unprocessed) else ''))
    machine += ['  }','}']
    return {'REQUIREMENTS.md' :'\n'.join(intro)+'\n','SOURCE-INDEX.md':'\n'.join(reverse)+'\n',
        'requirements/source-index.json':'\n'.join(machine)+'\n'}


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    records=[r for p in sorted((DATA/'records').glob('*.jsonl')) for r in v.lines(p)]
    outputs=render(records,v.lines(DATA/'dispositions.jsonl'),v.read(DATA/'ids.json'),v.load_sources())
    stale=[]
    for path,content in outputs.items():
        dest=DATA.parent/path; expected=content.encode('utf-8')
        if args.check:
            if not dest.exists() or dest.read_bytes()!=expected: stale.append(path)
        else: dest.write_bytes(expected)
    if stale: raise SystemExit('Stale generated files: '+', '.join(stale))
    print(f'{len(outputs)} generated files '+('checked' if args.check else 'written'))

if __name__=='__main__': main()
